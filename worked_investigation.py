"""Run one investigation for each role through the real agent and write WORKED_INVESTIGATION.md.

    python worked_investigation.py

The file records, for every role: the question, each tool call with its arguments, the exact SQL and parameters it ran,
row counts and truncation, the key results, and the agent's final answer. Uses the model provider configured in .env.
"""
import json
from datetime import date
from pathlib import Path

import agent
import tools

# One recurring pattern, seen from three roles: the BGL ciod job-loading / control-link failures (team job-runtime).
QUESTIONS = {
    "engineer": 'What is behind the "Link has been severed" errors in BGL? Show the failing lines, what happened around '
                "them, a possible cause and the next check.",
    "team_lead": "Over the whole BGL period, which problems recur, which teams own them, how are they trending, and what "
                 "should the team investigate first? Include OpenStack for comparison.",
    "manager": "Across BGL and OpenStack, what should we prioritise first, who should own each item, and what does the data "
               "not tell us?",
}


def _rows_preview(data, n=5):
    """First few rows of each list in a tool result, as compact JSON."""
    out = {}
    for k, v in (data or {}).items():
        out[k] = v[:n] if isinstance(v, list) else v
    return json.dumps(out, indent=1, default=str)[:3000]


def main():
    overview = tools.corpus_overview()
    md = [f"# Worked investigation\n",
          f"Generated by `python worked_investigation.py` on {date.today()} with model `{agent.label()}`"
          + (f" (effort `{agent.EFFORT}`)" if agent.PROVIDER == "anthropic" else "") + ". Every number below comes from a query that ran; the SQL is shown with each tool call.\n",
          "## Data scope\n",
          "| dataset | lines | problem lines | labelled alerts | first | last |", "|---|---|---|---|---|---|"]
    for d in overview["data"]["datasets"]:
        md.append(f"| {d['dataset']} | {d['lines']:,} | {d['problem_lines']:,} | {d['labelled_alerts']:,} | {d['first_ts']} | {d['last_ts']} |")
    md.append("\nA *problem line* has severity ≥ WARNING or a BGL expert alert label. Counts are log lines, not incidents.\n")

    for role, question in QUESTIONS.items():
        label = agent.ROLES[role]["label"]
        print(f"[{label}] {question}")
        md += [f"\n---\n\n## {label}\n", f"**Question:** {question}\n", "### Tool calls and evidence\n"]
        answer, calls = "", {}
        for ev in agent.run(agent.Session(role), question):
            if ev["type"] == "tool_call":
                calls[ev["id"]] = ev
                print(f"  {ev['id']} {ev['name']}")
            elif ev["type"] == "tool_result":
                c = calls[ev["id"]]
                md.append(f"#### {ev['id']} · `{c['name']}({json.dumps(c['input'])})`\n")
                if "error" in ev:
                    md.append(f"Error returned to the agent: `{ev['error']}`\n")
                    continue
                env = ev["envelope"]
                md.append(f"Scope: {env['scope']}\n")
                for q in env["queries"]:
                    md.append(f"- {q['purpose']}: {q['rows_returned']} rows{' (truncated)' if q['truncated'] else ''}\n"
                              f"  ```sql\n  {q['sql']}\n  ```\n  params: `{json.dumps(q['params'], default=str)}`")
                if env["notes"]:
                    md.append("\nNotes: " + " ".join(env["notes"]))
                md.append(f"\n<details><summary>Result (first rows)</summary>\n\n```json\n{_rows_preview(env['data'])}\n```\n</details>\n")
            elif ev["type"] == "answer":
                answer = ev["text"]
            elif ev["type"] == "error":
                answer = f"**Error:** {ev['text']}"
            elif ev["type"] == "done":
                u = ev["usage"]
                md.append(f"_{u['model_calls']} model calls, {u['input_tokens']:,} input / {u['output_tokens']:,} output tokens._\n")
        md += ["### Answer\n", answer, ""]

    md += ["\n---\n\n## What the data does and does not establish\n",
           "- Established: line counts, time spans, sources and owning teams for each pattern, computed in SereneDB over the loaded corpus.",
           "- Not established: root causes (candidate causes and lift are co-occurrence only), whether lines are separate incidents, "
           "and any downtime, user or cost impact, which the logs do not contain.",
           "- Team ownership comes from the `ownership` table loaded by `sql/schema.sql`."]
    Path(__file__).with_name("WORKED_INVESTIGATION.md").write_text("\n".join(md))
    print("wrote WORKED_INVESTIGATION.md")


if __name__ == "__main__":
    main()
